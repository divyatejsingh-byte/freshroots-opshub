// Turns the CSVs in /data into supabase/seed.sql (plain INSERT ... ON CONFLICT statements).
// Paste schema.sql, then seed.sql, into the Supabase SQL editor. No API key needed.
// Usage: npm run seed:sql
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function parseCsv(text) {
  const rows = [];
  let row = [], cell = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(cell); cell = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(cell); cell = "";
      if (row.some((c) => c.trim())) rows.push(row);
      row = [];
    } else cell += ch;
  }
  row.push(cell);
  if (row.some((c) => c.trim())) rows.push(row);
  const [header, ...body] = rows;
  return body.map((r) => Object.fromEntries(header.map((h, i) => [h.trim(), (r[i] ?? "").trim()])));
}

const read = (f) => parseCsv(readFileSync(join(root, "data", f), "utf8"));
const q = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === "" || v === undefined || Number.isNaN(Number(v)) ? "null" : String(Number(v)));

function insert(table, cols, rows, conflict, update) {
  const values = rows.map((r) => `  (${r.join(", ")})`).join(",\n");
  const set = update.map((c) => `${c} = excluded.${c}`).join(", ");
  return `insert into ${table} (${cols.join(", ")}) values\n${values}\non conflict (${conflict}) do update set ${set};\n`;
}

const prices = new Map(read("sku_prices.csv").map((r) => [r.SKU_ID, r]));
const parts = ["-- Generated by scripts/build-seed-sql.mjs from /data/*.csv. Safe to re-run.\n"];

parts.push(insert("distributors", ["id", "name", "region", "active"],
  read("distributor_master.csv").map((r) => [q(r.Distributor_ID), q(r.Distributor_Name), q(r.Region), r.Status.toLowerCase() === "active" ? "true" : "false"]),
  "id", ["name", "region", "active"]));

parts.push(insert("skus", ["id", "name", "category", "perishable", "reorder_qty", "unit_of_measure", "distributor_id", "unit_cost", "unit_price", "price_source"],
  read("sku_master.csv").map((r) => {
    const p = prices.get(r.SKU_ID);
    return [q(r.SKU_ID), q(r.SKU_Name), q(r.Category), r.Perishability.toLowerCase() === "high" ? "true" : "false", n(r.Standard_Reorder_Qty), q(r.Unit_of_Measure), q(r.Distributor_ID), n(p?.Unit_Cost), n(p?.Unit_Price), q(p?.Source ?? "assumed")];
  }),
  "id", ["name", "category", "perishable", "reorder_qty", "unit_of_measure", "distributor_id", "unit_cost", "unit_price", "price_source"]));

parts.push(insert("weekly_sales", ["sku_id", "week", "units_sold"],
  read("weekly_sales.csv").map((r) => [q(r.SKU_ID), q(r.Week), n(r.Units_Sold)]), "sku_id, week", ["units_sold"]));

parts.push(insert("inventory", ["sku_id", "location", "units_on_hand", "as_of_date"],
  read("current_inventory.csv").map((r) => [q(r.SKU_ID), q(r.Location), n(r.Units_On_Hand), q(r.As_Of_Date)]), "sku_id, location", ["units_on_hand", "as_of_date"]));

parts.push(insert("calendar", ["year_month", "year", "month", "is_festival_month"],
  read("calendar.csv").map((r) => [q(r.Year_Month), n(r.Year), n(r.Month), r.Is_Festival_Month.toUpperCase() === "TRUE" ? "true" : "false"]), "year_month", ["year", "month", "is_festival_month"]));

writeFileSync(join(root, "supabase", "seed.sql"), parts.join("\n"));
console.log("supabase/seed.sql written");
