// Inlines the CSVs in /data into lib/data/raw.ts so the same dataset loads in the browser and in server routes.
// Run `npm run data` after replacing any file in /data (dev and build run it automatically).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = {
  skuMaster: "sku_master.csv",
  weeklySales: "weekly_sales.csv",
  currentInventory: "current_inventory.csv",
  distributorMaster: "distributor_master.csv",
  calendar: "calendar.csv",
  skuPrices: "sku_prices.csv",
};

const out = Object.entries(files)
  .map(([key, file]) => `  ${key}: ${JSON.stringify(readFileSync(join(root, "data", file), "utf8").replace(/\r\n/g, "\n"))},`)
  .join("\n");

writeFileSync(
  join(root, "lib", "data", "raw.ts"),
  `// Generated by scripts/build-data.mjs from /data/*.csv. Do not edit by hand.\nexport const RAW = {\n${out}\n} as const;\n`
);
console.log("lib/data/raw.ts written from", Object.values(files).join(", "));
